// Builds the icon packs' style sheets, context-menu/icons/<pack>.css, from
// the icons chrome.css's "Restore icons" option gives menu items and
// context-menu/icons/packs.json, which says which of a pack's icons replaces
// each of Zen's (and, for a few items, which one an item gets instead). Run
// it after changing either:
//
//   node scripts/build_icon_packs.mjs
//
// tests/icon_packs.test.mjs fails while a style sheet is out of date.
//
// The style sheets list every item chrome.css gives an icon, with Zen's icon
// where the pack has none, so the pack's rules always win over chrome.css's
// (they're one :root more specific). They only set the icons (--menu-image);
// chrome.css's options show them. context-menu.uc.js loads them in each
// browser window, with their url()s made absolute: relative to the style
// sheet, they're in the chrome:// package the script runs from, and the
// icons take the menu's text color like Zen's.

import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

import { stripComments } from "./css_targets.mjs";

export const ICON_PACK_PREF = "uc.fixcontext.iconpack";

const OPTION = '@media -moz-pref("uc.fixcontext.restoreicons")';

/**
 * Splits a selector list at its top-level commas.
 *
 * @param {string} text
 * @returns {Array<string>} each selector on one line
 */
export function splitSelectors(text) {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const char of text) {
    if (char === "(" || char === "[") depth++;
    if (char === ")" || char === "]") depth--;
    if (char === "," && depth === 0) {
      parts.push(current);
      current = "";
    } else {
      current += char;
    }
  }
  parts.push(current);
  return parts
    .map((part) =>
      part
        .replace(/\s+/g, " ")
        .replace(/([([]) | ([)\]])/g, "$1$2")
        .trim(),
    )
    .filter(Boolean);
}

/**
 * The end of the block whose "{" is at `open`.
 *
 * @param {string} css
 * @param {number} open
 * @returns {number} the index of its "}"
 */
function blockEnd(css, open) {
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === "{") depth++;
    if (css[i] === "}" && --depth === 0) return i;
  }
  throw new Error("unbalanced braces");
}

/**
 * The icons chrome.css's "Restore icons" option gives menu items, in its
 * order.
 *
 * @param {string} css chrome.css
 * @returns {Array<{ selectors: Array<string>, url: string, flipped: boolean }>}
 *   `flipped` when the rule also mirrors the icon (Redo uses Undo's)
 */
export function iconRules(css) {
  const code = stripComments(css);
  const start = code.indexOf(OPTION);
  if (start < 0) {
    throw new Error(`chrome.css has no ${OPTION} block`);
  }
  const open = code.indexOf("{", start);
  const block = code.slice(open + 1, blockEnd(code, open));
  const rules = [];
  const rule = /([^{};]+)\{\s*--menu-image:\s*url\("([^"]+)"\);/g;
  for (const match of block.matchAll(rule)) {
    const [, selectors, url] = match;
    if (url.startsWith("data:")) continue;
    const body = block.slice(
      match.index + match[0].length,
      blockEnd(block, match.index + selectors.length),
    );
    rules.push({
      selectors: splitSelectors(selectors),
      url,
      flipped: /\btransform\s*:/.test(body),
    });
  }
  return rules;
}

/**
 * A pack's style sheet.
 *
 * @param {string} css chrome.css
 * @param {string} id the pack's id, the folder its icons are in
 * @param {{ name: string, icons: Record<string, string>, items: Record<string, string> }} pack
 *   its entry in packs.json: Zen's icon -> the pack's, and selector -> the
 *   pack's icon for items that get another one than their Zen icon's
 * @returns {string}
 */
export function buildPackCss(css, id, pack) {
  const lines = [
    `/* ${pack.name} icons for Calmer Context Menu's "Icons for every option"`,
    " * and quick actions. Generated by scripts/build_icon_packs.mjs from",
    " * chrome.css and packs.json: edit those, then run it again.",
    " *",
    " * The icons are from Context Menu Icons by Starry-AXQG",
    " * (https://github.com/Starry-AXQG/Context-Menu-Icons), MIT License: see",
    " * LICENSE in this folder. */",
    "",
    // Only the icons: chrome.css's options decide where they're shown.
    `@media -moz-pref("${ICON_PACK_PREF}", "${id}") {`,
    "  :root {",
  ];
  const rules = [];
  for (const { selectors, url, flipped } of iconRules(css)) {
    // Selectors of one chrome.css rule that get the same icon stay together.
    const groups = new Map();
    for (const selector of selectors) {
      const own = pack.items[selector];
      const file = own ?? pack.icons[url];
      const icon = file ? `${id}/${file}` : url;
      // An item with an icon of its own (Redo's) isn't mirrored.
      const unflip = flipped && !!own;
      const key = `${icon} ${unflip}`;
      if (!groups.has(key)) groups.set(key, { icon, unflip, selectors: [] });
      groups.get(key).selectors.push(selector);
    }
    rules.push(...groups.values());
  }
  for (const { icon, unflip, selectors } of rules) {
    lines.push(
      selectors.map((selector) => `    ${selector}`).join(",\n") + " {",
      `      --menu-image: url("${icon}");`,
    );
    if (unflip) {
      lines.push("      > .menu-icon {", "        transform: none;", "      }");
    }
    lines.push("    }");
  }
  lines.push("  }", "}", "");
  return lines.join("\n");
}

async function main() {
  const root = new URL("../", import.meta.url);
  const css = await readFile(new URL("chrome.css", root), "utf8");
  const packs = JSON.parse(
    await readFile(new URL("context-menu/icons/packs.json", root), "utf8"),
  );
  for (const [id, pack] of Object.entries(packs)) {
    const file = new URL(`context-menu/icons/${id}.css`, root);
    await writeFile(file, buildPackCss(css, id, pack));
    console.log(`Wrote context-menu/icons/${id}.css`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await main();
}
